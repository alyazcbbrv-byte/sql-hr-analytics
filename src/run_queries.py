"""
Run every query in sql/01_*.sql .. sql/06_*.sql against hr.db and write the results to
results/<name>.csv and one readable report, results/RESULTS.md.

Queries are separated by header comments:
    -- name: q01_top_earners
    -- title: ...
    -- question: ...

    python src/run_queries.py
"""
from __future__ import annotations

import csv
import re
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
SHOW_ROWS = 12


def parse(path: Path):
    text = path.read_text(encoding="utf-8")
    for block in re.split(r"(?m)^-- name:\s*", text)[1:]:
        name, rest = block.split("\n", 1)
        title = re.search(r"(?m)^-- title:\s*(.*)$", rest)
        question = re.search(r"(?m)^-- question:\s*(.*)$", rest)
        sql = "\n".join(l for l in rest.splitlines() if not re.match(r"^-- (title|question):", l)).strip()
        sql = re.split(r"(?m)^-- =+", sql)[0].strip()
        yield name.strip(), (title.group(1) if title else name), (question.group(1) if question else ""), sql


def fmt(v) -> str:
    if v is None:
        return ""
    if isinstance(v, float):
        return f"{v:,.2f}".rstrip("0").rstrip(".") if abs(v) < 1e6 else f"{v:,.0f}"
    if isinstance(v, int) and abs(v) >= 10000:
        return f"{v:,}"
    return str(v)


def md_table(cols, rows) -> str:
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    out += ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    db = ROOT / "hr.db"
    if not db.exists():
        print("hr.db not found: run  python src/build_db.py  first")
        return 1
    con = sqlite3.connect(db)
    RES.mkdir(exist_ok=True)
    report = ["# Query results", "",
              "Generated by `python src/run_queries.py`. Each section shows the question, the SQL and the first rows of the result "
              f"(full results are in the CSV files next to this report; at most {SHOW_ROWS} rows are shown here).", ""]
    n = 0
    for f in sorted((ROOT / "sql").glob("0[1-6]_*.sql")):
        report += [f"## {f.stem[3:].replace('_', ' ').title()}", ""]
        for name, title, question, sql in parse(f):
            cur = con.execute(sql)
            cols = [c[0] for c in cur.description]
            rows = cur.fetchall()
            with open(RES / f"{name}.csv", "w", encoding="utf-8", newline="") as fh:
                w = csv.writer(fh); w.writerow(cols); w.writerows(rows)
            more = f"\n\n_{len(rows)} rows in total; first {SHOW_ROWS} shown._" if len(rows) > SHOW_ROWS else ""
            report += [f"### {name.split('_', 1)[0].upper()}: {title}", "", f"**Question:** {question}", "",
                       "```sql", sql, "```", "", (md_table(cols, rows[:SHOW_ROWS]) + more if rows else "_No rows returned: the condition is not met by any record (the check passes)._"), ""]
            print(f"OK {name:42s} {len(rows):>4} rows")
            n += 1
    (RES / "RESULTS.md").write_text("\n".join(report), encoding="utf-8")
    print(f"\n{n} queries executed -> results/RESULTS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
